# Робочий день контакт-центру: 08:00 – 18:00
OPEN_HOUR = 8
N_HOURS = 10
DAY_LEN = N_HOURS * 3600.0          # тривалість робочого дня, с
BIN_SEC = 900.0                     # крок дискретизації станів системи (15 хв)
N_BINS = int(DAY_LEN / BIN_SEC)     # 40 інтервалів на добу

DEFAULT_SLA = 60.0                  # SLA: очікування відповіді ≤ 60 с
HOUR_LABELS = [f"{OPEN_HOUR + h:02d}–{OPEN_HOUR + h + 1:02d}" for h in range(N_HOURS)]

# Варіанти розподілу тривалості обслуговування
SERVICE_DISTS = {
    "Експоненційний": "exp",
    "Гамма (Ерланга)": "gamma",
    "Логнормальний": "lognorm",
    "Емпіричний (з даних)": "empirical",
    "Детермінований": "const",
}
SERVICE_DIST_NAMES = {v: k for k, v in SERVICE_DISTS.items()}


def fmt_clock(seconds: float) -> str:
    """Секунди від початку зміни -> ГГ:ХХ:СС (реальний час доби)."""
    s = int(max(0, seconds)) + OPEN_HOUR * 3600
    return f"{s // 3600:02d}:{(s % 3600) // 60:02d}:{s % 60:02d}"


def fmt_dur(seconds: float) -> str:
    """Тривалість у форматі ХХ:СС."""
    s = int(round(max(0, seconds)))
    return f"{s // 60:02d}:{s % 60:02d}"
